-- Platform metadata only. Cache entries are NEVER stored here: the cache stays in memory.
-- Portable SQL: runs unchanged on PostgreSQL (docker) and H2 (local dev).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    BIGINT       NOT NULL,
    updated_at    BIGINT       NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'OPERATOR', 'VIEWER'))
);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(64)  NOT NULL,
    action      VARCHAR(200) NOT NULL,
    target      VARCHAR(300),
    result      VARCHAR(40)  NOT NULL,
    ip_address  VARCHAR(64),
    created_at  BIGINT       NOT NULL
);
CREATE INDEX idx_audit_created ON audit_logs (created_at);
CREATE INDEX idx_audit_user ON audit_logs (username);

CREATE TABLE simulation_runs (
    id            VARCHAR(16)  PRIMARY KEY,
    node_id       VARCHAR(64)  NOT NULL,
    mode          VARCHAR(16)  NOT NULL,
    phase         VARCHAR(24)  NOT NULL,
    outcome       VARCHAR(40),
    started_at    BIGINT       NOT NULL,
    ended_at      BIGINT,
    detection_ms  BIGINT,
    failover_ms   BIGINT,
    recovery_ms   BIGINT,
    requests_total BIGINT,
    error_rate_pct DOUBLE PRECISION,
    report_json   VARCHAR(100000),
    events_json   VARCHAR(100000),
    created_at    BIGINT       NOT NULL,
    updated_at    BIGINT       NOT NULL
);
CREATE INDEX idx_sim_started ON simulation_runs (started_at);
CREATE INDEX idx_sim_node ON simulation_runs (node_id);

CREATE TABLE failover_history (
    id                    VARCHAR(16) PRIMARY KEY,
    node_id               VARCHAR(64) NOT NULL,
    detected_at           BIGINT NOT NULL,
    failover_started_at   BIGINT NOT NULL,
    failover_completed_at BIGINT NOT NULL,
    keys_promoted         INTEGER NOT NULL,
    re_replicated         INTEGER NOT NULL,
    trigger_type          VARCHAR(40) NOT NULL,
    created_at            BIGINT NOT NULL
);
CREATE INDEX idx_failover_node ON failover_history (node_id);

CREATE TABLE recommendations (
    id                 VARCHAR(16)  PRIMARY KEY,
    dedupe_key         VARCHAR(200) NOT NULL,
    category           VARCHAR(24)  NOT NULL,
    severity           VARCHAR(16)  NOT NULL,
    title              VARCHAR(300) NOT NULL,
    description        VARCHAR(2000),
    supporting_metric  VARCHAR(1000),
    reason             VARCHAR(2000),
    recommended_action VARCHAR(2000),
    status             VARCHAR(16)  NOT NULL,
    created_at         BIGINT       NOT NULL,
    updated_at         BIGINT       NOT NULL,
    CONSTRAINT chk_rec_status CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED', 'DISMISSED'))
);
CREATE INDEX idx_rec_status ON recommendations (status);

CREATE TABLE application_settings (
    setting_key   VARCHAR(100) PRIMARY KEY,
    setting_value VARCHAR(4000) NOT NULL,
    updated_at    BIGINT NOT NULL
);
